def get_development_info(
    birth_date: date,
    target_date: Optional[date] = None,
    week_override: Optional[int] = None
) -> Dict[str, Any]:
    """Возвращает актуальные развивающие упражнения, тайминги и скачок роста для возраста малыша."""
    if target_date is None:
        target_date = date.today()

    total_days = (target_date - birth_date).days
    if total_days < 0:
        total_days = 0

    actual_week = (total_days // 7) + 1
    selected_week = week_override if isinstance(week_override, int) else actual_week
    if selected_week < 1:
        selected_week = 1
    elif selected_week > 52:
        selected_week = 52

    # Получаем упражнения для выбранной недели (или берем ближайшую заполненную)
    if selected_week in WEEKLY_ACTIVITIES_DATABASE:
        week_data = WEEKLY_ACTIVITIES_DATABASE[selected_week]
    elif selected_week < 8:
        week_data = WEEKLY_ACTIVITIES_DATABASE[8]
    elif selected_week > 12:
        week_data = WEEKLY_ACTIVITIES_DATABASE[12]
    else:
        week_data = WEEKLY_ACTIVITIES_DATABASE[10]

    # Анализ скачков роста относительно текущей недели
    current_spurt = None
    next_spurt = None

    for spurt in GROWTH_SPURTS_CALENDAR:
        if spurt["start_week"] <= actual_week <= spurt["end_week"]:
            current_spurt = spurt
            break
        elif spurt["start_week"] > actual_week:
            if next_spurt is None or spurt["start_week"] < next_spurt["start_week"]:
                next_spurt = spurt

    is_spurt_active = current_spurt is not None
    if is_spurt_active:
        spurt_status_label = f"⚡️ Пик скачка №{current_spurt['spurt_num']} («{current_spurt['name']}»)"
        spurt_badge_class = "bg-amber-500/20 text-amber-400 border-amber-500/30"
        spurt_info = current_spurt
        days_left_in_spurt = (current_spurt["end_week"] * 7) - total_days
        spurt_countdown_text = f"Идет активная фаза (осталось ~{max(1, days_left_in_spurt)} дн.)"
    elif next_spurt:
        days_to_next = (next_spurt["start_week"] * 7) - total_days
        spurt_status_label = f"🟢 Спокойная фаза (интеграция навыков)"
        spurt_badge_class = "bg-emerald-500/20 text-emerald-400 border-emerald-500/30"
        spurt_info = next_spurt
        spurt_countdown_text = f"До скачка №{next_spurt['spurt_num']} («{next_spurt['name']}») осталось ~{max(1, days_to_next)} дн."
    else:
        spurt_status_label = "🟢 Стабильный период"
        spurt_badge_class = "bg-emerald-500/20 text-emerald-400 border-emerald-500/30"
        spurt_info = GROWTH_SPURTS_CALENDAR[-1]
        spurt_countdown_text = "Период спокойного закрепления навыков"

    start_day = (selected_week - 1) * 7 + 1
    end_day = selected_week * 7

    return {
        "actual_week": actual_week,
        "selected_week": selected_week,
        "is_actual_week": selected_week == actual_week,
        "total_days": total_days,
        "week_title": week_data["title"],
        "week_focus": week_data["focus"],
        "week_days_range": f"Дни {start_day}–{end_day}",
        "exercises": week_data["exercises"],
        "growth_spurt": {
            "is_active": is_spurt_active,
            "status_label": spurt_status_label,
            "badge_class": spurt_badge_class,
            "countdown_text": spurt_countdown_text,
            "spurt_num": spurt_info["spurt_num"],
            "spurt_name": spurt_info["name"],
            "description": spurt_info["description"],
            "symptoms": spurt_info["symptoms"],
            "parent_advice": spurt_info["parent_advice"]
        }
    }
